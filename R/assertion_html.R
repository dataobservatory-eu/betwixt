#' Render a semantic assertion as an interactive review cell
#'
#' Converts a single assertion from a prepared Betwixt review context into
#' the HTML representation used by the standalone review interface.
#'
#' The function determines how the assertion is presented to the reviewer
#' based on its candidate value, candidate range, and optional definition.
#' It also preserves the original assertion identity and candidate value
#' so that the review can subsequently be reconstructed by [read_review()].
#'
#' @param assertion A single assertion from a prepared review context,
#'   containing the following elements:
#'   \describe{
#'     \item{`name`}{The semantic column or property being reviewed.}
#'     \item{`value`}{The original candidate assertion value.}
#'     \item{`range`}{A character vector of permitted candidate values.
#'       An empty vector indicates that no controlled range is supplied.}
#'     \item{`definition`}{An optional URL identifying or defining the
#'       candidate value. May be `NA_character_`.}
#'   }
#'
#' @details
#' The function distinguishes between assertions with and without a
#' controlled candidate range.
#'
#' **Assertions without a candidate range**
#'
#' When no candidate range is supplied, the function renders:
#'
#' - A hyperlink when the assertion has a definition URL.
#' - A hyperlink when the candidate value is itself an HTTP(S) URL,
#'   except for assertions named `subject`.
#' - An editable text field and a "Create new item" button otherwise.
#'
#' These alternatives support both references to existing entities and
#' the creation of new entities during review.
#'
#' **Assertions with a candidate range**
#'
#' When a candidate range is supplied, the function renders a dropdown
#' containing the permitted values. The original candidate value is
#' selected when it matches one of the supplied range entries.
#'
#' A separate definition link is included when a definition URL exists.
#' The dropdown also includes a free-text input that is displayed by
#' the review interface when the reviewer selects a recognised
#' free-text option.
#'
#' **Special candidate-range values**
#'
#' Candidate ranges may contain reserved tokens with special meanings:
#'
#' \describe{
#'   \item{`Other…`, `Other...`, `<other>`}{
#'     Allow the reviewer to enter a replacement value outside the
#'     proposed candidate range. All three forms use the internal HTML
#'     value `__other__`. The Unicode ellipsis spelling `Other…` is
#'     retained for backward compatibility.
#'   }
#'   \item{`<unknown>`}{
#'     Indicates that an applicable value may exist but is unknown.
#'     Rendered with the label "Value unknown" and the internal HTML
#'     value `__unknown__`.
#'   }
#'   \item{`<no-value>`}{
#'     Indicates that no applicable value is possible.
#'     Rendered with the label "No value possible" and the internal
#'     HTML value `__no_value__`.
#'   }
#' }
#'
#' Reserved tokens are recognised only as complete candidate-range
#' entries. Ordinary values such as `Other`, `Unknown`, and `None`
#' retain their literal meanings.
#'
#' Special values are not automatically added to candidate ranges.
#' They must be explicitly supplied in the prepared review context.
#'
#' **Preservation of candidate state**
#'
#' The generated HTML table cell stores the assertion name in
#' `data-column` and the original candidate value in `data-candidate`.
#' The initial assertion qualification is stored as
#' `data-qualification="none"`.
#'
#' These attributes distinguish the original candidate assertion from
#' the reviewer's subsequent selection or correction. This separation
#' is essential for reconstructing the candidate and reviewed states
#' independently with [read_review()].
#'
#' The function also appends the assertion qualification controls
#' generated by `qualification_html()`. These controls allow the
#' reviewer to qualify an assertion independently of its value.
#'
#' @return A single character string containing the HTML table cell
#'   (`<td>`) representing the reviewable semantic assertion.
#'
#' @keywords internal
#' @noRd
assertion_html <- function(assertion) {
  value <- escape_html(assertion$value)
  has_definition <- !is.na(assertion$definition) &&
    nzchar(assertion$definition)
  is_url <- grepl(
    "^https?://",
    as.character(assertion$value),
    ignore.case = TRUE
  )

  if (length(assertion$range) == 0) {
    # Link a resolved entity, link a URL value, or allow creation of an
    # unresolved one.
    if (has_definition) {
      control <- paste0(
        '<a class="entity-link" href="',
        escape_html(assertion$definition),
        '" target="_blank" rel="noopener">',
        value,
        "</a>"
      )
    } else if (is_url && assertion$name != "subject") {
      control <- paste0(
        '<a class="entity-link" href="',
        escape_html(assertion$value),
        '" target="_blank" rel="noopener">',
        value,
        "</a>"
      )
    } else {
      control <- paste0(
        '<input class="subject-input" type="text" value="',
        value,
        '">',
        '<button type="button" class="create-item">',
        "Create new item",
        "</button>"
      )
    }
  } else {
    options <- vapply(assertion$range, function(option) {
      # Recognise reserved range tokens and legacy spellings.
      special <- switch(option,
        "Other\u2026" = "__other__",
        "Other..." = "__other__",
        "<other>" = "__other__",
        "<unknown>" = "__unknown__",
        "<no-value>" = "__no_value__",
        NULL
      )

      option_value <- if (is.null(special)) option else special

      option_label <- switch(option,
        "Other\u2026" = "Other [curator entered]",
        "Other..." = "Other [curator entered]",
        "<other>" = "Other [curator entered]",
        "<unknown>" = "Value unknown",
        "<no-value>" = "No value possible",
        option
      )

      selected <- if (identical(option, assertion$value)) {
        " selected"
      } else {
        ""
      }

      paste0(
        '<option value="', escape_html(option_value), '"',
        selected, ">",
        escape_html(option_label),
        "</option>"
      )
    }, character(1))

    control <- paste0(
      '<select class="candidate-select">',
      paste(options, collapse = ""),
      "</select>",
      '<input class="write-in" placeholder="Enter another value">'
    )
  }

  definition <- ""

  # Controlled assertions retain a separate definition link.
  if (length(assertion$range) > 0 && has_definition) {
    definition <- paste0(
      '<a class="definition-link" href="',
      escape_html(assertion$definition),
      '" target="_blank" rel="noopener">Definition</a>'
    )
  }

  # Preserve the assertion identity and original candidate value.
  paste0(
    '<td class="semantic-cell" data-column="',
    escape_html(assertion$name),
    '" data-qualification="none" data-candidate="',
    value,
    '">',
    control,
    definition,
    qualification_html(),
    "</td>"
  )
}
